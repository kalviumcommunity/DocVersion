import json
import math
import os
from pathlib import Path
from typing import Dict, List, Tuple

from dotenv import load_dotenv
from openai import OpenAI


# Project paths
ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = ROOT / "outputs"

VECTOR_OUTPUT = OUTPUT_DIR / "embedding_sample_vectors.json"
REPORT_OUTPUT = OUTPUT_DIR / "embedding_demo_report.md"

MODEL_NAME = "text-embedding-3-small"


# Include similar texts and a clearly unrelated text.
SAMPLE_TEXTS = {
    "text_1": (
        "Employees can request paid leave from their manager."
    ),
    "text_2": (
        "Workers may ask their supervisor for paid time off."
    ),
    "text_3": (
        "The company requires employees to follow security policies."
    ),
    "text_4": (
        "Saturn is a planet with a large system of rings."
    ),
}


def cosine_similarity(
    vector_a: List[float],
    vector_b: List[float],
) -> float:
    """Calculate cosine similarity between two vectors."""

    if len(vector_a) != len(vector_b):
        raise ValueError(
            "Vectors must have the same dimension."
        )

    dot_product = sum(
        a * b for a, b in zip(vector_a, vector_b)
    )

    norm_a = math.sqrt(sum(a * a for a in vector_a))
    norm_b = math.sqrt(sum(b * b for b in vector_b))

    if norm_a == 0 or norm_b == 0:
        raise ValueError(
            "Cosine similarity is undefined for zero vectors."
        )

    return dot_product / (norm_a * norm_b)


def generate_embeddings(
    texts: Dict[str, str],
) -> Tuple[Dict[str, List[float]], str]:
    """
    Generate real embeddings through the OpenAI API.

    If the API key is unavailable, return a clear error rather
    than silently substituting fake vectors.
    """

    load_dotenv(ROOT / ".env")

    api_key = os.getenv("OPENAI_API_KEY")

    if not api_key:
        raise RuntimeError(
            "OPENAI_API_KEY is missing. Add it to your .env "
            "file to generate real embeddings."
        )

    client = OpenAI(api_key=api_key)

    response = client.embeddings.create(
        model=MODEL_NAME,
        input=list(texts.values()),
    )

    vectors = {}

    for key, item in zip(texts.keys(), response.data):
        vectors[key] = item.embedding

    return vectors, MODEL_NAME


def make_report(
    texts: Dict[str, str],
    vectors: Dict[str, List[float]],
    model_used: str,
) -> str:
    """Create a report containing dimensions and comparisons."""

    dimensions = {
        len(vector) for vector in vectors.values()
    }

    if len(dimensions) != 1:
        raise ValueError(
            "Embedding vectors do not all have the same dimension."
        )

    dimension = dimensions.pop()

    similar_score = cosine_similarity(
        vectors["text_1"],
        vectors["text_2"],
    )

    unrelated_score = cosine_similarity(
        vectors["text_1"],
        vectors["text_4"],
    )

    report = [
        "# Embedding Demonstration",
        "",
        "## Model",
        "",
        "- Model: `{}`".format(model_used),
        "- Number of texts: {}".format(len(texts)),
        "- Vector dimension: {}".format(dimension),
        "- All vectors have the same dimension: Yes",
        "",
        "## Sample texts",
        "",
    ]

    for key, text in texts.items():
        report.append("- **{}:** {}".format(key, text))

    report.extend([
        "",
        "## Similarity comparison",
        "",
        "| Pair | Cosine similarity |",
        "|---|---:|",
        "| Similar meaning: text_1 vs text_2 | {:.6f} |".format(
            similar_score
        ),
        "| Unrelated meaning: text_1 vs text_4 | {:.6f} |".format(
            unrelated_score
        ),
        "",
        "## Interpretation",
        "",
        (
            "Cosine similarity compares the direction of two "
            "embedding vectors. A higher score indicates that "
            "the vectors point in more similar directions."
        ),
        "",
        (
            "The similar pair should score higher than the "
            "unrelated pair for this demonstration. Actual "
            "scores depend on the embedding model."
        ),
        "",
        "## What embeddings represent",
        "",
        (
            "An embedding is a numeric representation of text "
            "generated by a trained model. The numbers encode "
            "features of the text's meaning and context. They "
            "are not random IDs and are not simple keyword counts."
        ),
        "",
        "## Why embeddings enable semantic search",
        "",
        (
            "A query and a document passage can be converted "
            "into vectors and compared by similarity. This helps "
            "retrieve relevant passages even when the query and "
            "passage use different words to express similar ideas."
        ),
        "",
    ])

    return "\n".join(report)


def main() -> None:
    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    print("Generating text embeddings...")

    try:
        vectors, model_used = generate_embeddings(SAMPLE_TEXTS)
    except Exception as exc:
        print("\n[ERROR] Could not generate embeddings: {}".format(exc))
        print(
            "\nAdd a valid OPENAI_API_KEY to your .env file, "
            "then run this script again."
        )
        return

    dimensions = [
        len(vector) for vector in vectors.values()
    ]

    if not dimensions or len(set(dimensions)) != 1:
        raise ValueError(
            "All samples must have vectors of the same length."
        )

    dimension = dimensions[0]

    print("\nModel: {}".format(model_used))
    print("Number of texts: {}".format(len(vectors)))
    print("Vector dimensions: {}".format(dimensions))
    print("Vector dimension: {}".format(dimension))
    print("All vectors have equal dimensions: Yes")

    # Print a small preview, rather than flooding the terminal.
    for key, vector in vectors.items():
        print(
            "{} preview: {}".format(
                key,
                [round(value, 6) for value in vector[:8]],
            )
        )

    similar_score = cosine_similarity(
        vectors["text_1"],
        vectors["text_2"],
    )

    unrelated_score = cosine_similarity(
        vectors["text_1"],
        vectors["text_4"],
    )

    print("\nCosine similarity comparisons:")
    print(
        "Similar pair (text_1 vs text_2): {:.6f}".format(
            similar_score
        )
    )
    print(
        "Unrelated pair (text_1 vs text_4): {:.6f}".format(
            unrelated_score
        )
    )

    if similar_score > unrelated_score:
        print(
            "\nPASS: The similar pair scored higher "
            "than the unrelated pair."
        )
    else:
        print(
            "\nWARNING: The expected score ordering was not observed."
        )

    # Store actual vectors for reproducibility.
    vector_data = {
        "model": model_used,
        "dimension": dimension,
        "texts": SAMPLE_TEXTS,
        "vectors": vectors,
    }

    with VECTOR_OUTPUT.open("w", encoding="utf-8") as file:
        json.dump(
            vector_data,
            file,
            indent=2,
        )

    report = make_report(
        SAMPLE_TEXTS,
        vectors,
        model_used,
    )

    with REPORT_OUTPUT.open("w", encoding="utf-8") as file:
        file.write(report)

    print("\nSaved vectors to: {}".format(VECTOR_OUTPUT))
    print("Saved report to: {}".format(REPORT_OUTPUT))


if __name__ == "__main__":
    main()