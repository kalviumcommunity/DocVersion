
"""
End-to-end RAG pipeline for DocVersion.

Stages:
1. Embed: Create a query embedding if OpenAI credentials are available.
2. Retrieve: Search ChromaDB when possible, otherwise use lexical search.
3. Assemble: Build context while retaining source metadata.
4. Generate: Use an LLM when available, otherwise return a clearly
   labelled extractive answer from retrieved text.

Offline mode does not perform semantic embeddings or LLM generation.
"""

import json
import math
import os
import re
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = ROOT / "outputs"
CHUNKS_FILE = OUTPUT_DIR / "sample_chunks.json"
DB_PATH = OUTPUT_DIR / "chroma_db"
COLLECTION_NAME = "docversion_chunks"
SAMPLE_OUTPUT = OUTPUT_DIR / "rag_pipeline_sample.md"

EMBEDDING_MODEL = "text-embedding-3-small"
GENERATION_MODEL = "gpt-4o-mini"
TOP_K = 3

STOPWORDS = {
    "a", "an", "and", "are", "as", "at", "be", "by", "for",
    "from", "in", "is", "it", "of", "on", "or", "that", "the",
    "this", "to", "was", "were", "with", "can", "may", "must",
    "should", "their", "they", "you", "your", "we", "our",
    "what", "does", "how", "where", "when", "which", "about",
    "many", "much", "each", "year", "years", "do", "did",
}


# ============================================================
# 1. Load the existing chunk corpus
# ============================================================

def load_chunks() -> List[Dict[str, Any]]:
    """Load and validate chunks generated by the earlier pipeline."""

    if not CHUNKS_FILE.exists():
        raise FileNotFoundError(
            "Chunk file not found: {}. Run the document chunking "
            "step first.".format(CHUNKS_FILE)
        )

    with CHUNKS_FILE.open("r", encoding="utf-8") as file:
        chunks = json.load(file)

    if not isinstance(chunks, list) or not chunks:
        raise ValueError("The chunk corpus is empty or invalid.")

    for chunk in chunks:
        if not isinstance(chunk, dict):
            raise ValueError("Every chunk must be a JSON object.")

        if not chunk.get("chunk_id"):
            raise ValueError("A chunk is missing its chunk_id.")

        if not isinstance(chunk.get("text"), str):
            raise ValueError(
                "Chunk {} is missing text.".format(chunk.get("chunk_id"))
            )

        if not isinstance(chunk.get("metadata", {}), dict):
            raise ValueError(
                "Metadata must be an object for chunk {}.".format(
                    chunk["chunk_id"]
                )
            )

    return chunks


# ============================================================
# Shared text utilities
# ============================================================

def tokenize(text: str) -> List[str]:
    """Normalize text into simple lexical tokens."""

    words = re.findall(r"\b[a-z0-9]+\b", text.lower())

    return [
        word for word in words
        if word not in STOPWORDS
    ]


def clean_text(text: str) -> str:
    """Remove common Markdown heading markers and excess whitespace."""

    text = re.sub(r"(?m)^\s{0,3}#{1,6}\s*", "", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


# ============================================================
# 2. Embed the query
# ============================================================

def embed_query(query: str) -> Dict[str, Any]:
    """
    Create a real query embedding when possible.

    If credentials or the embedding service are unavailable, return
    a labelled lexical representation instead.
    """

    api_key = os.getenv("OPENAI_API_KEY")

    if api_key:
        try:
            from openai import OpenAI

            client = OpenAI(api_key=api_key)
            response = client.embeddings.create(
                model=EMBEDDING_MODEL,
                input=[query],
            )

            return {
                "mode": "vector",
                "model": EMBEDDING_MODEL,
                "vector": response.data[0].embedding,
                "tokens": tokenize(query),
            }

        except Exception as exc:
            print(
                "[WARNING] Query embedding failed: {}. "
                "Falling back to lexical mode.".format(exc)
            )

    return {
        "mode": "offline_lexical",
        "model": None,
        "vector": None,
        "tokens": tokenize(query),
    }


# ============================================================
# 3. Retrieve relevant chunks
# ============================================================

def lexical_retrieve(
    query: str,
    chunks: List[Dict[str, Any]],
    k: int = TOP_K,
) -> List[Dict[str, Any]]:
    """
    Rank chunks using weighted keyword overlap.

    This is lexical matching, not semantic vector retrieval.
    """

    query_terms = set(tokenize(query))

    if not query_terms:
        return []

    prepared = []
    document_frequency = Counter()

    for chunk in chunks:
        text = chunk.get("text", "").strip()
        terms = set(tokenize(text))

        prepared.append((chunk, text, terms))
        document_frequency.update(terms)

    total_chunks = len(chunks)
    query_weights = {
        term: math.log(
            1.0 + (
                (total_chunks + 1.0)
                / (document_frequency.get(term, 0) + 1.0)
            )
        )
        for term in query_terms
    }

    denominator = sum(query_weights.values())

    if denominator <= 0:
        return []

    scored = []

    for chunk, text, terms in prepared:
        matched_terms = query_terms.intersection(terms)

        if not matched_terms:
            continue

        score = sum(
            query_weights[term] for term in matched_terms
        ) / denominator

        # A heading-only chunk is weak evidence.
        if len(terms) < 4:
            score *= 0.25

        # Prefer substantive text over empty or tiny chunks.
        if len(text) < 30:
            score *= 0.5

        scored.append({
            "chunk_id": chunk["chunk_id"],
            "text": text,
            "metadata": chunk.get("metadata", {}),
            "score": score,
            "retrieval_method": "offline_keyword",
        })

    scored.sort(
        key=lambda item: (-item["score"], item["chunk_id"])
    )

    return scored[:max(0, k)]


def vector_retrieve(
    query_vector: List[float],
    k: int = TOP_K,
) -> Optional[List[Dict[str, Any]]]:
    """
    Retrieve from the existing ChromaDB collection.

    Returns None when the database or collection is unavailable.
    """

    try:
        import chromadb

        if not DB_PATH.exists():
            return None

        client = chromadb.PersistentClient(path=str(DB_PATH))
        collection = client.get_collection(
            name=COLLECTION_NAME
        )

        count = collection.count()

        if count == 0:
            return None

        response = collection.query(
            query_embeddings=[query_vector],
            n_results=min(k, count),
            include=["documents", "metadatas", "distances"],
        )

        ids = response.get("ids", [[]])[0]
        documents = response.get("documents", [[]])[0]
        metadatas = response.get("metadatas", [[]])[0]
        distances = response.get("distances", [[]])[0]

        results = []

        for chunk_id, text, metadata, distance in zip(
            ids, documents, metadatas, distances
        ):
            results.append({
                "chunk_id": chunk_id,
                "text": text or "",
                "metadata": metadata or {},
                # ChromaDB distances are distances, not relevance scores.
                "score": float(distance),
                "retrieval_method": "chromadb_vector_distance",
            })

        return results

    except Exception as exc:
        print(
            "[WARNING] Vector retrieval unavailable: {}. "
            "Falling back to lexical retrieval.".format(exc)
        )
        return None


def retrieve(
    query: str,
    query_representation: Dict[str, Any],
    chunks: List[Dict[str, Any]],
    k: int = TOP_K,
) -> List[Dict[str, Any]]:
    """Select relevant chunks using the available retrieval method."""

    if query_representation.get("mode") == "vector":
        results = vector_retrieve(
            query_representation["vector"],
            k=k,
        )

        if results is not None:
            return results

    return lexical_retrieve(query, chunks, k=k)


# ============================================================
# 4. Assemble grounded context and source metadata
# ============================================================

def assemble_context(
    results: List[Dict[str, Any]],
) -> Tuple[str, List[Dict[str, Any]]]:
    """Build context blocks and a traceable source list."""

    context_parts = []
    sources = []

    for index, result in enumerate(results, start=1):
        metadata = result.get("metadata", {})
        source = metadata.get("source", "Unknown source")
        section = metadata.get("section", "")
        chunk_id = result["chunk_id"]

        label = "[{}] Source: {}; Chunk: {}".format(
            index,
            source,
            chunk_id,
        )

        if section:
            label += "; Section: {}".format(section)

        context_parts.append(
            "{}\n{}".format(label, result["text"].strip())
        )

        sources.append({
            "citation_id": index,
            "chunk_id": chunk_id,
            "source": source,
            "source_path": metadata.get("source_path", ""),
            "section": section,
            "page": metadata.get("page"),
            "chunk_index": metadata.get("chunk_index"),
            "score": result.get("score"),
            "retrieval_method": result.get("retrieval_method"),
        })

    return "\n\n".join(context_parts), sources


# ============================================================
# 5. Generate an answer from retrieved context
# ============================================================

def extractive_answer(
    query: str,
    results: List[Dict[str, Any]],
) -> Tuple[str, str]:
    """
    Select relevant sentences directly from retrieved chunks.

    This fallback does not generate new facts or claim to be an LLM.
    """

    query_terms = set(tokenize(query))
    evidence = []
    seen = set()

    for index, result in enumerate(results, start=1):
        metadata = result.get("metadata", {})
        source = metadata.get("source", "Unknown source")
        chunk_id = result.get("chunk_id", "")

        # Use the same citation ID as assemble_context().
        label = "[{}]".format(index)
        passage = clean_text(result.get("text", ""))

        if not passage:
            continue

        sentences = re.split(r"(?<=[.!?])\s+", passage)

        for sentence in sentences:
            sentence = sentence.strip()
            sentence_terms = set(tokenize(sentence))

            if not sentence or not sentence_terms:
                continue

            # Keep only sentences sharing meaningful query terms.
            if not query_terms.intersection(sentence_terms):
                continue

            key = sentence.lower()

            if key in seen:
                continue

            seen.add(key)
            evidence.append(
                "{} {}".format(label, sentence)
            )

    if not evidence:
        return (
            "The retrieved documents do not contain enough "
            "matching evidence to answer this question reliably.",
            "no_sufficient_evidence",
        )

    answer = (
        "Offline extractive answer (not generated by an LLM):\n"
        + "\n".join(evidence)
    )

    return answer, "extractive_fallback"


def generate_answer(
    query: str,
    context: str,
    results: List[Dict[str, Any]],
) -> Tuple[str, str]:
    """
    Use an LLM if configured, otherwise return an extractive answer.

    No retrieved context means no grounded answer should be generated.
    """

    if not results or not context.strip():
        return (
            "I couldn't find relevant information in the available "
            "documents, so I can't provide a grounded answer.",
            "no_evidence",
        )

    api_key = os.getenv("OPENAI_API_KEY")

    if api_key:
        try:
            from openai import OpenAI

            client = OpenAI(api_key=api_key)
            response = client.chat.completions.create(
                model=GENERATION_MODEL,
                temperature=0,
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "Answer using only the supplied context. "
                            "Do not invent facts. If the evidence is "
                            "insufficient, say so. Cite evidence with "
                            "the context labels, such as [1] and [2]."
                        ),
                    },
                    {
                        "role": "user",
                        "content": (
                            "Question:\n{}\n\n"
                            "Retrieved context:\n{}"
                        ).format(query, context),
                    },
                ],
            )

            answer = response.choices[0].message.content

            if answer and answer.strip():
                return answer.strip(), "llm_generation"

        except Exception as exc:
            print(
                "[WARNING] LLM generation failed: {}. "
                "Using extractive fallback.".format(exc)
            )

    return extractive_answer(query, results)


# ============================================================
# 6. End-to-end orchestration
# ============================================================

def run_rag(query: str) -> Dict[str, Any]:
    """Run the complete embed -> retrieve -> assemble -> generate flow."""

    query = query.strip()

    if not query:
        raise ValueError("The query cannot be empty.")

    print("\n[1/4] Embedding query representation...")
    query_representation = embed_query(query)
    print("Query mode: {}".format(query_representation["mode"]))

    chunks = load_chunks()

    print("\n[2/4] Retrieving relevant chunks...")
    results = retrieve(
        query=query,
        query_representation=query_representation,
        chunks=chunks,
        k=TOP_K,
    )
    print("Retrieved chunks: {}".format(len(results)))

    print("\n[3/4] Assembling grounded context...")
    context, sources = assemble_context(results)
    print("Context characters: {}".format(len(context)))

    print("\n[4/4] Generating answer...")
    answer, generation_mode = generate_answer(
        query=query,
        context=context,
        results=results,
    )
    print("Answer mode: {}".format(generation_mode))

    return {
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "query": query,
        "query_mode": query_representation["mode"],
        "retrieval_mode": (
            results[0]["retrieval_method"]
            if results
            else "no_results"
        ),
        "generation_mode": generation_mode,
        "answer": answer,
        "sources": sources,
        "retrieved_chunks": results,
    }


# ============================================================
# 7. Save sample output for the assignment
# ============================================================

def save_sample_output(result: Dict[str, Any]) -> None:
    """Save the real run result as a Markdown report."""

    lines = [
        "# End-to-End RAG Sample Run",
        "",
        "- Timestamp: {}".format(result["timestamp"]),
        "- Query: {}".format(result["query"]),
        "- Query mode: {}".format(result["query_mode"]),
        "- Retrieval mode: {}".format(result["retrieval_mode"]),
        "- Generation mode: {}".format(result["generation_mode"]),
        "",
        "## Answer",
        "",
        result["answer"],
        "",
        "## Retrieved sources",
        "",
    ]

    if result["sources"]:
        for source in result["sources"]:
            lines.append(
                "- **[{}] {}** — chunk `{}`; section: `{}`; "
                "page: `{}`".format(
                    source["citation_id"],
                    source["source"],
                    source["chunk_id"],
                    source["section"],
                    source["page"],
                )
            )
    else:
        lines.append("No sources were retrieved.")

    lines.extend([
        "",
        "## Retrieved chunk previews",
        "",
    ])

    for chunk in result["retrieved_chunks"]:
        metadata = chunk.get("metadata", {})

        lines.extend([
            "### {}".format(chunk["chunk_id"]),
            "",
            "- Source: {}".format(
                metadata.get("source", "Unknown source")
            ),
            "- Section: {}".format(
                metadata.get("section", "")
            ),
            "- Retrieval method: {}".format(
                chunk.get("retrieval_method", "")
            ),
            "- Score/distance: {}".format(
                chunk.get("score")
            ),
            "",
            chunk.get("text", "")[:500],
            "",
        ])

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    SAMPLE_OUTPUT.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )


# ============================================================
# 8. Main entry point
# ============================================================

def main() -> None:
    query = os.getenv(
        "RAG_QUERY",
        "How many days of annual leave do employees receive each year?",
    )

    result = run_rag(query)
    save_sample_output(result)

    print("\n========== FINAL ANSWER ==========")
    print(result["answer"])

    print("\n========== SOURCES ==========")

    if result["sources"]:
        for source in result["sources"]:
            print(
                "[{}] {} | chunk={} | section={}".format(
                    source["citation_id"],
                    source["source"],
                    source["chunk_id"],
                    source["section"],
                )
            )
    else:
        print("No sources found.")

    print("\nSaved sample run to: {}".format(SAMPLE_OUTPUT))


if __name__ == "__main__":
    main()
